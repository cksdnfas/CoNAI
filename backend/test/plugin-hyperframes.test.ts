import './support/testTemp'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import os from 'node:os'
import { test } from 'node:test'
import AdmZip from 'adm-zip'

test('installed HyperFrames manages shared projects with revision-safe saves and account-scoped output history', { timeout: process.env.HYPERFRAMES_RENDER_TEST === '1' ? 900000 : 120000 }, async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'conai-hyperframes-integration-'))
  process.env.RUNTIME_BASE_PATH = path.join(root, 'private')
  for (const part of ['DATABASE', 'UPLOADS', 'LOGS', 'TEMP', 'SAVE', 'CANVAS', 'ARTIFACTS', 'MODELS', 'CUSTOM_NODES', 'RECYCLE_BIN']) process.env[`RUNTIME_${part}_DIR`] = path.join(root, part.toLowerCase())
  const authModule = await import('../src/database/authDb')
  authModule.initializeAuthDb()
  const auth = authModule.getAuthDb()
  const main = await import('../src/database/init')
  await main.initializeDatabase()
  const user = await import('../src/database/userSettingsDb')
  user.initializeUserSettingsDb()
  const registry = await import('../src/services/plugins/pluginRegistry')
  const runtime = await import('../src/services/plugins/pluginServerRuntime')
  const tools = await import('../src/services/plugins/pluginServerTools')
  const { RuntimeJobRunner } = await import('../src/services/runtimeJobs/runtimeJobRunner')
  t.after(async () => {
    RuntimeJobRunner.shutdown()
    await runtime.closePluginServers()
    await new Promise(resolve => setTimeout(resolve, 200))
    auth.close(); user.closeUserSettingsDb(); main.closeDatabase()
    await new Promise<void>(async resolve => (await import('../src/utils/logger')).logger.close(resolve))
    assert.ok(path.basename(root).startsWith('conai-hyperframes-integration-'))
    fs.rmSync(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 })
  })
  const adminId = Number(auth.prepare("INSERT INTO auth_accounts(username,password_hash,account_type) VALUES ('hyperframes-test','unused','admin')").run().lastInsertRowid)
  const { AuthPermissionGroup } = await import('../src/models/AuthPermissionGroup')
  const group = AuthPermissionGroup.createCustomGroup({ name: 'hyperframes-test', permissionKeys: ['content.read', 'content.edit', 'content.delete', 'page.generation.view'] })
  AuthPermissionGroup.addAccountMembership(group.id, adminId)
  ;(await import('../src/services/auth/sessionAccess')).invalidateConfiguredAuthCache()
  const actor = { accountId: adminId, accountType: 'admin' as const }
  const source = path.join(root, 'uploads', 'source.png')
  fs.mkdirSync(path.dirname(source), { recursive: true })
  await (await import('sharp')).default({ create: { width: 320, height: 180, channels: 3, background: 'red' } }).png().toFile(source)
  const hash = 'ab'.repeat(24)
  main.db.prepare('INSERT OR IGNORE INTO watched_folders(folder_path,folder_name) VALUES(?,?)').run(path.dirname(source), 'test-library')
  const folderId = (main.db.prepare('SELECT id FROM watched_folders WHERE folder_path=?').get(path.dirname(source)) as { id: number }).id
  main.db.prepare("INSERT INTO media_metadata(composite_hash,postprocess_status,rating_score,prompt,width,height) VALUES(?,'ready',1,'hyperframes integration red image',320,180)").run(hash)
  main.db.prepare("INSERT INTO image_files(composite_hash,original_file_path,folder_id,file_size,mime_type,file_status) VALUES(?,?,?,?,'image/png','active')").run(hash, source, folderId, fs.statSync(source).size)
  const before = fs.readFileSync(source)
  const zip = new AdmZip()
  const plugins = path.resolve(__dirname, '../../plugins')
  zip.addLocalFolder(path.join(plugins, 'hyperframes'), '', entry => !/\.md$/i.test(entry))
  zip.addLocalFile(path.join(plugins, 'sdk/conai-plugin.js'))
  zip.addLocalFile(path.join(plugins, 'sdk/conai-plugin.css'))
  registry.unpackPlugin(zip.toBuffer())
  await registry.installPlugin(zip.toBuffer())
  runtime.startPluginServers()
  await registry.setPluginEnabled('hyperframes', true, adminId)
  const until = async (fn: () => boolean | Promise<boolean>, ms = 90000) => {
    const deadline = Date.now() + ms
    while (!await fn()) { if (Date.now() > deadline) throw new Error('Timed out'); await new Promise(resolve => setTimeout(resolve, 100)) }
  }
  await until(() => runtime.pluginServerStatus('hyperframes').state === 'ready')
  const unpack = (result: any): any => {
    assert.notEqual(result.isError, true, JSON.stringify(result))
    return JSON.parse(result.content.find((p: any) => p.type === 'text').text)
  }
  const call = async (name: string, args: Record<string, unknown> = {}) => unpack(await tools.callPluginServerTool(`p_hyperframes_${name}`, args, actor))
  const { callTrustedAppTool } = await import('../src/services/plugins/pluginAppBridge')
  const found = unpack(await callTrustedAppTool(actor, 'search_images', { search_text: 'hyperframes integration', limit: 5 }))
  assert.ok(found.images.some((image: any) => image.composite_hash === hash))
  const bound = await call('inspect_assets', { assets: [{ id: 'photo', reference: { source: 'library', compositeHash: hash } }] })
  const { starter } = await import('../../plugins/hyperframes/project.mjs')
  const project = { ...starter('내부 이미지 영상', bound.assets), width: 320, height: 180, duration: 1 }
  const saved = await call('save_project', { document: JSON.stringify(project), requestId: 'integration-save-123' })
  assert.match(saved.revision, /^[a-f0-9]{64}$/)
  const updated = await call('save_project', { fileId: saved.fileId, revision: saved.revision, document: JSON.stringify({ ...saved.project, title: '수정한 제목' }), requestId: 'integration-edit-123' })
  const conflict = await tools.callPluginServerTool('p_hyperframes_save_project', { fileId: saved.fileId, revision: saved.revision, document: JSON.stringify(project), requestId: 'integration-conflict-123' }, actor)
  assert.equal(conflict.isError, true)
  await t.test('rename, archive and duplicate preserve the original and stale drafts cannot overwrite it', async () => {
    const listed = await call('list_projects', { query: '수정한 제목' })
    assert.equal(listed.items[0].fileId, saved.fileId)
    const archived = await call('save_project', { fileId: updated.fileId, revision: updated.revision, document: JSON.stringify({ ...updated.project, stage: 'archived' }), requestId: 'integration-archive-123' })
    assert.equal((await call('list_projects')).items.length, 0)
    assert.equal((await call('list_projects', { stage: 'archived' })).items[0].fileId, saved.fileId)
    const copy = await call('save_project', { document: JSON.stringify({ ...archived.project, title: '복사본', stage: 'draft' }), requestId: 'integration-copy-123' })
    assert.notEqual(copy.fileId, saved.fileId)
    assert.equal((await call('read_project', { fileId: saved.fileId })).project.stage, 'archived')
    const stale = await tools.callPluginServerTool('p_hyperframes_save_project', { fileId: saved.fileId, revision: saved.revision, document: JSON.stringify(project), requestId: 'integration-recovered-draft' }, actor)
    assert.equal(stale.isError, true)
    Object.assign(updated, archived)
  })
  await t.test('listing is paginated and file access remains required', async () => {
    for (let i = 0; i < 21; i++) await call('save_project', { document: JSON.stringify(starter(`페이지 프로젝트 ${i}`)), requestId: `integration-page-${i}` })
    const first = await call('list_projects', { query: '페이지 프로젝트' })
    const second = await call('list_projects', { query: '페이지 프로젝트', offset: first.nextOffset })
    assert.equal(first.items.length, 20); assert.equal(second.items.length, 1); assert.equal(second.nextOffset, null)
    assert.equal(new Set([...first.items, ...second.items].map(x => x.fileId)).size, 21)
    const deniedId = Number(auth.prepare("INSERT INTO auth_accounts(username,password_hash,account_type) VALUES ('no-files','unused','guest')").run().lastInsertRowid)
    const denied = await tools.callPluginServerTool('p_hyperframes_list_projects', {}, { accountId: deniedId, accountType: 'guest' })
    assert.equal(denied.isError, true)
  })
  await t.test('legacy documents join the catalog when opened without changing their contents', async () => {
    const legacy = unpack(await callTrustedAppTool(actor, 'write_text_file', { name: 'HyperFrames-legacy.json', text: JSON.stringify(starter('기존 프로젝트')) }))
    assert.equal((await call('list_projects', { query: '기존 프로젝트' })).total, 0)
    const read = await call('read_project', { fileId: legacy.id })
    assert.equal(read.revision, legacy.revision)
    assert.equal((await call('list_projects', { query: '기존 프로젝트' })).items[0].fileId, legacy.id)
    unpack(await callTrustedAppTool(actor, 'delete_files', { file_ids: [legacy.id] }))
    const missing = await tools.callPluginServerTool('p_hyperframes_read_project', { fileId: legacy.id }, actor)
    assert.equal(missing.isError, true)
    assert.equal((await call('list_projects', { query: '기존 프로젝트' })).total, 0)
    const longTitle = '한'.repeat(100)
    const longProject = await call('save_project', { document: JSON.stringify(starter(longTitle)), requestId: 'integration-long-title-123' })
    assert.equal((await call('read_project', { fileId: longProject.fileId })).project.title, longTitle)
  })
  await t.test('storyboard scenes round-trip, the list shows a cover, and only administrators may install the renderer', async () => {
    const listed = await call('list_projects', { stage: 'all', query: '수정한 제목' })
    assert.equal(listed.items[0].cover, `library:${hash}`)
    const read = await call('read_project', { fileId: updated.fileId })
    assert.deepEqual(read.project.scenes, [{ asset: 'photo', seconds: 4, caption: '내부 이미지 영상' }])
    const status = await call('renderer_status')
    assert.equal(typeof status.browser.ok, 'boolean'); assert.equal(status.package.ok, false); assert.equal(status.canInstall, true); assert.equal(status.install.status, 'idle')
    const guestId = Number(auth.prepare("INSERT INTO auth_accounts(username,password_hash,account_type) VALUES ('renderer-guest','unused','guest')").run().lastInsertRowid)
    const refused = await tools.callPluginServerTool('p_hyperframes_install_renderer', {}, { accountId: guestId, accountType: 'guest' })
    assert.equal(refused.isError, true)
    assert.equal((await call('renderer_status')).install.status, 'idle')
  })
  await t.test('real rendering persists output references and isolates job history by account', { skip: process.env.HYPERFRAMES_RENDER_TEST !== '1' }, async () => {
  await call('install_renderer')
  await until(async () => (await call('renderer_status')).install.status !== 'running', 600000)
  assert.equal((await call('renderer_status')).ready, true, JSON.stringify(await call('renderer_status')))
  const submitted = await call('render', { fileId: updated.fileId, revision: updated.revision, requestId: 'integration-render-123' })
  assert.match(submitted.jobId, /^[a-f0-9-]{36}$/)
  let done: any
  await until(async () => { done = await call('job_status', { jobId: submitted.jobId }); return ['completed', 'failed', 'cancelled'].includes(done.status) })
  assert.equal(done.status, 'completed', JSON.stringify(done))
  assert.match(done.result.compositeHash, /^(?:[a-f0-9]{32}|[a-f0-9]{48})$/)
  assert.equal(done.result.projectRevision, updated.revision)
  assert.equal(done.result.sources[0].reference.compositeHash, hash)
  const { findLibraryMedia } = await import('../src/services/sprite/spriteLibrary')
  assert.equal(findLibraryMedia(done.result.compositeHash)?.mimeType, 'video/mp4')
  assert.deepEqual(fs.readFileSync(source), before, 'original library image is unchanged')
  const duplicate = await call('render', { fileId: updated.fileId, revision: updated.revision, requestId: 'integration-render-123' })
  assert.equal(duplicate.jobId, submitted.jobId)
  const history = await call('project_history', { fileId: updated.fileId })
  assert.equal(history.items.length, 1)
  assert.equal(history.items[0].compositeHash, done.result.compositeHash)
  assert.equal(history.items[0].revision, updated.revision)
  const otherId = Number(auth.prepare("INSERT INTO auth_accounts(username,password_hash,account_type) VALUES ('other-renderer','unused','admin')").run().lastInsertRowid)
  AuthPermissionGroup.addAccountMembership(group.id, otherId)
  ;(await import('../src/services/auth/sessionAccess')).invalidateConfiguredAuthCache()
  const other = unpack(await tools.callPluginServerTool('p_hyperframes_project_history', { fileId: updated.fileId }, { accountId: otherId, accountType: 'admin' }))
  assert.deepEqual(other.items, [])
  await registry.setPluginEnabled('hyperframes', false, adminId)
  await registry.setPluginEnabled('hyperframes', true, adminId)
  await until(() => runtime.pluginServerStatus('hyperframes').state === 'ready')
  assert.equal((await call('project_history', { fileId: updated.fileId })).items[0].compositeHash, done.result.compositeHash)
  assert.equal((await call('list_projects', { stage: 'archived' })).items[0].fileId, updated.fileId)
  })
})
